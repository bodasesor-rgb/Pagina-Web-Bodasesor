#!/usr/bin/env node
/**
 * Generate unique hub×city SEO copy with Gemini (reduces thin template duplicates).
 *
 * Usage:
 *   node scripts/generate-city-hub-content.mjs --hub=banquetes
 *   node scripts/generate-city-hub-content.mjs --hub=banquetes,barras-de-bebidas --city=leon
 *   node scripts/generate-city-hub-content.mjs --hub=banquetes --force
 *
 * Auth: GEMINI_API_KEY / GEMINI_IA or GOOGLE_SERVICE_ACCOUNT_JSON
 * Model: gemini-3.1-flash-lite (see scripts/lib/gemini-config.mjs)
 */
import { writeFileSync, mkdirSync, readFileSync, existsSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { CITY_MAP } from '../src/data/city-data.js'
import { CITY_LOCAL_CONTEXT } from '../src/data/city-local-context.js'
import { SPA_SEO_HUBS } from '../src/data/spa-seo-hubs.js'
import { geminiGenerate, parseGeminiJson } from './lib/gemini.mjs'
import { GEMINI_TEXT_MODEL } from './lib/gemini-config.mjs'

const __dirname = dirname(fileURLToPath(import.meta.url))
const ROOT = join(__dirname, '..')
const OUT_JSON = join(ROOT, 'src/data/city-hub-content.json')
const OUT_JS = join(ROOT, 'src/data/city-hub-content.js')

function parseArgs(argv) {
  const out = { hubs: [], cities: [], force: false, limit: 0 }
  for (const a of argv) {
    if (a === '--force') out.force = true
    else if (a.startsWith('--hub=')) out.hubs = a.slice(6).split(',').map((s) => s.trim()).filter(Boolean)
    else if (a.startsWith('--city=')) out.cities = a.slice(7).split(',').map((s) => s.trim()).filter(Boolean)
    else if (a.startsWith('--limit=')) out.limit = Number(a.slice(8)) || 0
  }
  return out
}

function uniqueCities() {
  const map = new Map()
  for (const c of Object.values(CITY_MAP)) {
    if (!map.has(c.slug)) map.set(c.slug, c)
  }
  return [...map.values()]
}

function loadStore() {
  if (!existsSync(OUT_JSON)) return {}
  return JSON.parse(readFileSync(OUT_JSON, 'utf8'))
}

function writeStore(store) {
  mkdirSync(dirname(OUT_JSON), { recursive: true })
  const sorted = Object.fromEntries(Object.entries(store).sort(([a], [b]) => a.localeCompare(b)))
  writeFileSync(OUT_JSON, `${JSON.stringify(sorted, null, 2)}\n`)
  writeFileSync(
    OUT_JS,
    `/** Auto-generated by scripts/generate-city-hub-content.mjs — do not edit by hand. */\n` +
      `import data from './city-hub-content.json'\n\n` +
      `/** @typedef {{ h1: string, headline: string, description: string[], seoTitle: string, seoDescription: string, localBullets: string[], faqs: {q:string,a:string}[] }} CityHubContent */\n\n` +
      `/** @type {Record<string, CityHubContent>} */\n` +
      `export const CITY_HUB_CONTENT = data\n\n` +
      `export function getCityHubContent(hubSlug, citySlug) {\n` +
      `  if (!hubSlug || !citySlug) return null\n` +
      `  return CITY_HUB_CONTENT[\`\${hubSlug}/\${citySlug}\`] || null\n` +
      `}\n`,
  )
}

function hubMeta(hubSlug) {
  const path = hubSlug.startsWith('/') ? hubSlug : `/${hubSlug}`
  return SPA_SEO_HUBS.find((h) => h.path === path) || null
}

function buildPrompt({ hub, city, local }) {
  const zones = (local?.zones || []).join(', ')
  return `Eres copywriter SEO senior para Bodasesor (eventos y banquetes en México).
Reescribe la landing de servicio para UNA ciudad concreta. El sitio hoy solo cambia el nombre de la ciudad (contenido duplicado); tú debes crear copy ÚNICO y útil.

Servicio (hub): ${hub.title} (slug: ${hub.path.replace(/^\//, '')})
Descripción base del hub: ${hub.desc}
Ciudad: ${city.name} (slug: ${city.slug})${city.short ? `, abreviatura ${city.short}` : ''}
Estado/región: ${local?.state || 'México'}
Zonas/colonias reales a mencionar (elige 2–4 con naturalidad): ${zones || 'zona metropolitana'}
Contexto local: ${local?.notes || 'Eventos sociales y corporativos en la región.'}

Reglas:
- Español de México, tono profesional cercano Bodasesor.
- NO inventes precios, testimonios con nombres, ni venues/negocios inventados.
- SÍ menciona zonas reales, tipo de celebración típica y logística local.
- El texto NO debe servir si solo sustituyes el nombre de la ciudad por otra.
- seoTitle ≤ 60 caracteres si es posible; seoDescription ≤ 155 caracteres.
- description: 3 párrafos (strings), cada uno 2–4 oraciones.
- localBullets: 3–5 bullets cortos específicos de la ciudad.
- faqs: exactamente 3 pares {q,a} útiles para esa ciudad + servicio.
- h1 debe incluir el servicio y la ciudad.
- Responde SOLO JSON válido con exactamente estas claves:
{
  "h1": string,
  "headline": string,
  "description": string[3],
  "seoTitle": string,
  "seoDescription": string,
  "localBullets": string[],
  "faqs": [{"q": string, "a": string}]
}`
}

function validateContent(obj, cityName) {
  if (!obj || typeof obj !== 'object') throw new Error('not an object')
  for (const k of ['h1', 'headline', 'seoTitle', 'seoDescription']) {
    if (typeof obj[k] !== 'string' || obj[k].trim().length < 8) throw new Error(`bad ${k}`)
  }
  if (!Array.isArray(obj.description) || obj.description.length < 2) throw new Error('bad description')
  if (!Array.isArray(obj.localBullets) || obj.localBullets.length < 2) throw new Error('bad localBullets')
  if (!Array.isArray(obj.faqs) || obj.faqs.length < 2) throw new Error('bad faqs')
  // Soft check: city name should appear somewhere
  const blob = JSON.stringify(obj)
  if (!blob.toLowerCase().includes(cityName.toLowerCase().slice(0, 4))) {
    console.warn(`  warn: city name "${cityName}" barely present in output`)
  }
  return {
    h1: obj.h1.trim(),
    headline: obj.headline.trim(),
    description: obj.description.map((s) => String(s).trim()).filter(Boolean),
    seoTitle: obj.seoTitle.trim(),
    seoDescription: obj.seoDescription.trim(),
    localBullets: obj.localBullets.map((s) => String(s).trim()).filter(Boolean),
    faqs: obj.faqs.map((f) => ({ q: String(f.q || f.question || '').trim(), a: String(f.a || f.answer || '').trim() })),
  }
}

async function main() {
  const args = parseArgs(process.argv.slice(2))
  const hubs = (args.hubs.length ? args.hubs : ['banquetes']).map((h) => h.replace(/^\//, ''))
  const cities = uniqueCities().filter((c) => !args.cities.length || args.cities.includes(c.slug))
  const store = loadStore()

  console.log(`Gemini model: ${GEMINI_TEXT_MODEL} (cost-optimized + context cache)`)
  console.log(`Hubs: ${hubs.join(', ')} | cities: ${cities.length} | force=${args.force}`)

  let done = 0
  let skipped = 0
  let failed = 0

  for (const hubSlug of hubs) {
    const hub = hubMeta(hubSlug)
    if (!hub) {
      console.error(`Unknown hub (not in SPA_SEO_HUBS): ${hubSlug}`)
      process.exit(1)
    }
    for (const city of cities) {
      if (args.limit && done >= args.limit) break
      const key = `${hubSlug}/${city.slug}`
      if (!args.force && store[key]) {
        skipped++
        continue
      }
      const local = CITY_LOCAL_CONTEXT[city.slug]
      process.stdout.write(`→ ${key} ... `)
      try {
        const text = await geminiGenerate(buildPrompt({ hub, city, local }), {
          json: true,
          temperature: 0.9,
          useCache: true,
          model: GEMINI_TEXT_MODEL,
        })
        const parsed = validateContent(parseGeminiJson(text), city.name)
        store[key] = {
          ...parsed,
          hub: hubSlug,
          city: city.slug,
          generatedAt: new Date().toISOString(),
          model: GEMINI_TEXT_MODEL,
        }
        writeStore(store)
        done++
        console.log('ok')
        await new Promise((r) => setTimeout(r, 400))
      } catch (e) {
        failed++
        console.log(`FAIL ${e.message}`)
      }
    }
  }

  writeStore(store)
  console.log(`Done. generated=${done} skipped=${skipped} failed=${failed} totalKeys=${Object.keys(store).length}`)
  console.log(`Wrote ${OUT_JSON}`)
  if (failed) process.exitCode = 1
}

main().catch((e) => {
  console.error(e)
  process.exit(1)
})
